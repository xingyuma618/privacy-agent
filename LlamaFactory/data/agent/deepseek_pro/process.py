def process_messages(messages):
    new_messages = []
    for msg in messages:
        if msg.get("role") == "assistant":
            # 获取原有的content，如果为None则设为空字符串
            content = msg.get("content") or ""
            
            # 检查是否存在tool_calls
            if "tool_calls" in msg and msg["tool_calls"]:
                for tool_call in msg["tool_calls"]:
                    if tool_call.get("type") == "function":
                        func = tool_call.get("function", {})
                        
                        args = func.get("arguments", "{}")
                        if isinstance(args, str):
                            try:
                                args = json.loads(args)
                            except json.JSONDecodeError:
                                pass # 如果解析失败，保留原字符串
                        
                        func_dict = {
                            "name": func.get("name", ""),
                            "arguments": args
                        }
                        
                        func_str = json.dumps(func_dict, ensure_ascii=False)
                        
                        content += f"\n{TOOL_CALL_START}\n{func_str}\n{TOOL_CALL_END}"
            
            new_msg = {
                "role": "assistant",
                "content": content.strip()
            }
            new_messages.append(new_msg)
        else:
            new_messages.append(msg)
            
    return new_messages

def main():
    os.makedirs(os.path.dirname(output_file_path), exist_ok=True)
    
    with open(input_file_path, 'r', encoding='utf-8') as infile, \
         open(output_file_path, 'w', encoding='utf-8') as outfile:
        
        for line in infile:
            if not line.strip():
                continue
                
            data = json.loads(line)
            
            # 1. 处理 messages
            if "messages" in data:
                data["messages"] = process_messages(data["messages"])
            
            # 2. 注入 tools 字段，将其转化为 JSON 字符串！
            # 关键修复点：使用 json.dumps 将列表转为字符串
            data["tools"] = json.dumps(TOOLS_DEF, ensure_ascii=False)
            
            # 写入 jsonl
            outfile.write(json.dumps(data, ensure_ascii=False) + "\n")
            
    print(f"数据处理完成！已包含 tools 字段。保存至: {output_file_path}")

if __name__ == "__main__":
    main()